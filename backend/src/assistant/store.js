function complete(state) {
  for (const key of COLLECTIONS) state[key] ||= {};
  return state;
}

export function createMemoryStore(seed = emptyState()) {
  let state = complete(clone(seed));
  let queue = Promise.resolve();
  return {
    mode: 'memory-test',
    async read(fn = (value) => value) { await queue; return fn(clone(state)); },
    transaction(fn) {
      const operation = queue.then(async () => {
        const draft = clone(state);
        const result = await fn(draft);
        state = draft;
        return clone(result);
      });
      queue = operation.catch(() => {});
      return operation;
    }
  };
}

/** Single-host, synthetic-only demo persistence. Atomic rename and an exclusive file lock prevent lost updates. */
export function createFileStore(filePath, { seed = createSyntheticState() } = {}) {
  const absolutePath = path.resolve(filePath);
  const lockPath = `${absolutePath}.lock`;
  async function withLock(fn) {
    await mkdir(path.dirname(absolutePath), { recursive: true, mode: 0o700 });
    let lock;
    const deadline = Date.now() + 10000;
    while (!lock) {
      try { lock = await open(lockPath, 'wx', 0o600); }
      catch (error) {
        if (error.code !== 'EEXIST') throw error;
        if (Date.now() > deadline) throw new Error('Demo storage is busy. Retry shortly; check for a stale lock after an interrupted process.');
        await new Promise((resolve) => setTimeout(resolve, 25));
      }
    }
    try { return await fn(); }
    finally { await lock.close(); await unlink(lockPath); }
  }
  async function load() {
    try { return complete(JSON.parse(await readFile(absolutePath, 'utf8'))); }
    catch (error) { if (error.code === 'ENOENT') return complete(clone(seed)); throw error; }
  }
  async function save(state) {
    const temporary = `${absolutePath}.${randomUUID()}.tmp`;
    await writeFile(temporary, JSON.stringify(state), { encoding: 'utf8', mode: 0o600 });
    await rename(temporary, absolutePath);
  }
  return {
    mode: 'synthetic-file-demo',
    read(fn = (state) => state) { return withLock(async () => { const state = await load(); await save(state); return clone(await fn(clone(state))); }); },
    transaction(fn) { return withLock(async () => { const state = await load(); const result = await fn(state); await save(state); return clone(result); }); }
  };
}

