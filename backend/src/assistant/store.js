const GENERIC = ['prescriptions', 'conversations', 'confirmations', 'notifications', 'toolExecutions', 'auditEvents', 'paymentWebhookEvents'];
const clone = (value) => structuredClone(value);
export const emptyState = () => Object.fromEntries(COLLECTIONS.map((key) => [key, {}]));

